# --- Styles ----------------------------------------------------------------

BODY_SIZE = 10
base = ParagraphStyle("base", fontName="Times-Roman", fontSize=BODY_SIZE, leading=12.6)
styles = {
    "name": ParagraphStyle("name", base, fontName="Times-Bold", fontSize=20, leading=24, alignment=TA_CENTER),
    "contact": ParagraphStyle("contact", base, alignment=TA_CENTER),
    "section": ParagraphStyle("section", base, fontName="Times-Bold", fontSize=11, leading=13, spaceBefore=8),
    "left": base,
    "right": ParagraphStyle("right", base, alignment=TA_RIGHT),
    "body": base,
    "bullet": ParagraphStyle("bullet", base, leading=12.2),
}

PAGE_W, _ = A4
MARGIN = 1.8 * cm
FRAME_PADDING = 6  # SimpleDocTemplate frames pad 6pt on each side
TEXT_W = PAGE_W - 2 * MARGIN - 2 * FRAME_PADDING
DATE_W = 3.8 * cm


def section(title):
    return [
        Paragraph(title.upper(), styles["section"]),
        HRFlowable(width="100%", thickness=0.6, color="black", spaceBefore=1, spaceAfter=4),
    ]


def row(left, right):
    """One line with text on the left and text flush right (place or dates)."""
    table = Table(
        [[Paragraph(left, styles["left"]), Paragraph(right, styles["right"])]],
        colWidths=[TEXT_W - DATE_W, DATE_W],
    )
    table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    return table


def bullets(items):
    return ListFlowable(
        [ListItem(Paragraph(text, styles["bullet"]), leftIndent=12, bulletColor="black") for text in items],
        bulletType="bullet",
        start="•",
        bulletFontName="Times-Roman",
        bulletFontSize=BODY_SIZE,
        leftIndent=12,
        spaceBefore=2,
    )


def build():
    story = [
        Paragraph(NAME, styles["name"]),
        Spacer(1, 2),
        Paragraph("  |  ".join(CONTACT), styles["contact"]),
        *section("Profile"),
        Paragraph(PROFILE, styles["body"]),
        *section("Experience"),
    ]

    for i, job in enumerate(EXPERIENCE):
        if i:
            story.append(Spacer(1, 6))
        story += [
            row(f"<b>{job['org']}</b>", job["place"]),
            row(f"<i>{job['role']}</i>", job["dates"]),
            bullets(job["bullets"]),
        ]

    story += section("Selected projects")
    for i, project in enumerate(PROJECTS):
        if i:
            story.append(Spacer(1, 6))
        story += [
            row(f"<b>{project['name']}</b>, <i>{project['context']}</i>", project["dates"]),
            Paragraph(f"<i>{project['stack']}</i>", styles["body"]),
            bullets(project["bullets"]),
        ]

    story += section("Education")
    for i, item in enumerate(EDUCATION):
        if i:
            story.append(Spacer(1, 4))
        story += [
            row(f"<b>{item['org']}</b>", item["place"]),
            row(f"<i>{item['role']}</i>", item["dates"]),
        ]

    story += section("Skills")
    for label, value in SKILLS:
        story.append(Paragraph(f"<b>{label}:</b> {value}", styles["body"]))

    doc = SimpleDocTemplate(
        str(OUTPUT),
        pagesize=A4,
        leftMargin=MARGIN,
        rightMargin=MARGIN,
        topMargin=1.3 * cm,
        bottomMargin=1.3 * cm,
        title=f"{NAME} – CV",
        author=NAME,
    )
    doc.build(story)
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    build()
